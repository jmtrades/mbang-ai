def totals(rows: list[dict]) -> dict:
    by: dict[str, dict] = {}
    for r in rows:
        sec = r["id"][0]
        b = by.setdefault(sec, {"score": 0, "max": 0, "rows": 0})
        b["score"] += r["score"]
        b["max"] += 2
        b["rows"] += 1
    return by
